/**
 * `report [dir] [--out FILE] [--sample N] [--replay N]`: grade distribution per file, hint-search statistics over the
 * first N records of every file, and the R-001 hand-check sample (N per level: 3/4 New game, 1/4 Daily) as Markdown.
 */
object ReportCmd {
    /** Fixed seed so the hand-check sample is the same every run. */
    private const val SAMPLE_SEED = 0x48414E44L // "HAND"

    fun run(args: List<String>, out: (String) -> Unit): Int {
        val opts = Options.parse(args)
        val dir = bankDir(opts.positional.firstOrNull())
        val outFile = File(opts.value("out") ?: "build/m1-hand-check.md")
        val perLevel = opts.int("sample") ?: 20
        val replayN = opts.int("replay") ?: Int.MAX_VALUE
        val records = BankFile.ALL.associateWith { bf -> BankCodec.decodeAll(bf.bytes(dir)) }
        if (records.values.all { it.isEmpty() }) {
            out("report: no bank in '$dir'")
            return 1
        }

        val md = StringBuilder()
        val distribution = distribution(records)
        distribution.forEach(out)
        val replay = replayStats(records, replayN)
        replay.forEach(out)
        md.append(header(records.values.sumOf { it.size }, perLevel, replayN))
        md.append("## Grade distribution\n\n```text\n").append(distribution.joinToString("\n")).append("\n```\n\n")
        md.append("## Hint search over whole solves\n\n")
        md.append("Every record (or the first N with `--replay N`) was solved by taking a hint at every state and applying its placement ")
        md.append("(true candidates, as US-012 requires). Checks: every placement equals the solution digit, no elimination ever removes a ")
        md.append("solution digit, and no fallback is needed on a bank puzzle (TC-112). Timings are JVM wall-clock on the machine that ran the report.\n\n")
        md.append("```text\n").append(replay.joinToString("\n")).append("\n```\n\n")
        md.append(sample(records, perLevel))
        outFile.parentFile?.mkdirs()
        outFile.writeText(md.toString())
        out("report: hand-check sample written to $outFile")
        return 0
    }

    private fun header(total: Int, perLevel: Int, replayN: Int): String = """
        |# M1 hand-check sample (R-001)
        |
        |> Generated by `lantern-generator report` from `bank/v1` ($total records). Owner: Engineering · Re-run after any bank change.
        |
        |This file supports the R-001 hand check (US-013, TC-121). For each level it lists $perLevel puzzles chosen with a fixed seed
        |(15 New game + 5 Daily per level), each with its givens, its grade, the full technique trace of the engine's simplest-first
        |solve, and an **independent cross-check**: the solution from the validator's DLX counter (Algorithm X, separate code), the
        |solution from the engine's backtracking solver, and the logical solution must all be equal, and the solve must succeed with
        |only the level's techniques.
        |
        |**Still recommended before release:** a human, or a reference solver such as HoDoKu used only as a tool (ADR-003), should
        |solve these puzzles and confirm that nothing above the level is needed (TC-121). The automated cross-check proves
        |uniqueness and that the ladder suffices; it can't prove that our grade matches how a human (or another solver) perceives
        |the difficulty, because the grader and the trace below are the same engine. Hint replay: ${if (replayN == Int.MAX_VALUE) "every record" else "the first $replayN records of every file"}.
        |
        |How to read a trace: `Technique in <house(s)> → rRcC = d` places a digit; `→ remove d from rRcC` lists eliminations.
        |Rows, columns and boxes are numbered 1–9; boxes in reading order.
        |
        |""".trimMargin()

    internal fun distribution(records: Map<BankFile, List<BankRecord>>): List<String> {
        val lines = ArrayList<String>()
        val techs = Technique.entries
        lines += "%-20s %6s  %s   givens min/avg/max".format("file", "count", techs.joinToString(" ") { "%3s".format(it.code) })
        for ((bf, list) in records) {
            if (list.isEmpty()) continue
            val byTech = techs.map { t -> list.count { it.hardest == t } }
            val g = list.map { it.givens.filledCount }
            lines += "%-20s %6d  %s   %d/%.1f/%d".format(
                bf.name, list.size, byTech.joinToString(" ") { "%3d".format(it) }, g.min(), g.average(), g.max(),
            )
        }
        lines += "codes: " + techs.joinToString(", ") { "${it.code} = ${it.label}" }
        return lines
    }

    internal fun replayStats(records: Map<BankFile, List<BankRecord>>, n: Int): List<String> {
        val lines = ArrayList<String>()
        lines += "%-20s %7s %7s %7s %6s %6s %9s %6s %8s %7s".format(
            "file", "puzzles", "hints", "chains", "depth", "shown", "fallbacks", "wrong", "mean µs", "max ms",
        )
        val total = ReplayStats()
        for ((bf, list) in records) {
            val stats = parallelMap(minOf(n, list.size)) { i ->
                val g = list[i].givens
                HintReplay.replay(g, BacktrackingSolver.solve(g)!!)
            }
            val s = ReplayStats().also { acc -> stats.forEach(acc::add) }
            total.add(s)
            lines += row(bf.name, stats.size, s)
        }
        lines += row("all", records.values.sumOf { minOf(n, it.size) }, total)
        lines += "depth = most eliminations the search applied before a single appeared; shown = most steps in a hint after pruning"
        lines += "chain rate ${"%.2f".format(100.0 * total.chains / maxOf(1, total.hints))}% of hints (LLD §4.4: bring to the PM if > 5%)"
        return lines
    }

    private fun row(name: String, puzzles: Int, s: ReplayStats): String = "%-20s %7d %7d %7d %6d %6d %9d %6d %8.1f %7.2f".format(
        name, puzzles, s.hints, s.chains, s.maxSearchDepth, s.maxShownSteps, s.fallbacks, s.wrongPlacements + s.badEliminations,
        s.meanMicros, s.maxMillis,
    )

    private fun sample(records: Map<BankFile, List<BankRecord>>, perLevel: Int): String {
        val rng = SplitMix64(SAMPLE_SEED)
        val md = StringBuilder()
        for (level in Level.entries) {
            md.append("## ${level.name.lowercase().replaceFirstChar { it.uppercase() }}\n\n")
            val daily = perLevel / 4
            val picks = pick(rng, records, Pool.NEWGAME, level, perLevel - daily) + pick(rng, records, Pool.DAILY, level, daily)
            md.append("| ID | Givens | Hardest | Steps | Cross-check |\n|---|---|---|---|---|\n")
            val entries = picks.map { (id, r) -> id to describe(r) }
            for ((id, e) in entries) md.append("| `$id` | ${e.givens} | ${e.hardest} | ${e.steps} | ${if (e.ok) "OK" else "**MISMATCH**"} |\n")
            md.append('\n')
            for ((id, e) in entries) md.append(e.block(id))
        }
        return md.toString()
    }

    private fun pick(rng: SplitMix64, records: Map<BankFile, List<BankRecord>>, pool: Pool, level: Level, n: Int): List<Pair<PuzzleId, BankRecord>> {
        val list = records[BankFile(pool, level)].orEmpty()
        if (list.isEmpty()) return emptyList()
        val chosen = sortedSetOf<Int>()
        while (chosen.size < minOf(n, list.size)) chosen += rng.nextInt(list.size)
        return chosen.map { PuzzleId(pool, level, it) to list[it] }
    }

    private class Entry(
        val givens: Int,
        val hardest: String,
        val steps: Int,
        val ok: Boolean,
        val check: String,
        val board: String,
        val text: String,
        val trace: List<String>,
    ) {
        fun block(id: PuzzleId): String = buildString {
            append("### `$id` · $hardest · $givens givens\n\n")
            append("`$text`\n\n```text\n").append(board).append("```\n\n")
            append("Cross-check: $check\n\n<details><summary>Technique trace ($steps steps)</summary>\n\n")
            trace.forEachIndexed { i, s -> append(i + 1).append(". ").append(s).append('\n') }
            append("\n</details>\n\n")
        }
    }

    private fun describe(r: BankRecord): Entry {
        val g = r.givens
        val grade = Grader.grade(g)
        val dlx = DlxCounter().count(g, 2)
        val bt = BacktrackingSolver.solve(g)
        val restricted = LogicalSolver.forLevel(r.level).solve(g)
        val ok = dlx.count == 1 && BacktrackingSolver.countSolutions(g) == 1 && dlx.firstSolution == bt && bt == grade.solution &&
            restricted.solved && restricted.grid == bt && grade.hardest == r.hardest
        val check = if (ok) {
            "OK: DLX = 1 and backtracking = 1 solution; DLX = backtracking = logical solution; solved with ${r.level} techniques only; " +
                "re-grade = stored code `${r.hardest.code}`"
        } else {
            "**MISMATCH** (DLX ${dlx.count}, re-grade ${grade.hardest}, stored ${r.hardest})"
        }
        return Entry(g.filledCount, grade.hardest?.label ?: "stuck", grade.steps.size, ok, check, pretty(g), g.toString(), grade.steps.map { it.describe() })
    }

    private fun pretty(g: Grid): String = buildString {
        for (r in 0 until 9) {
            if (r % 3 == 0 && r > 0) append("------+-------+------\n")
            for (c in 0 until 9) {
                if (c % 3 == 0 && c > 0) append("| ")
                val v = g[r * 9 + c]
                append(if (v == 0) '.' else ('0' + v)).append(if (c == 8) "" else " ")
            }
            append('\n')
        }
    }
}
